CREATE TABLE IF NOT EXISTS audit_seals (
    seal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sealed_at_epoch_ms BIGINT NOT NULL,
    window_start_epoch_ms BIGINT NOT NULL,
    to_event_id BIGINT,
    head_hash CHAR(64) NOT NULL,
    event_count BIGINT NOT NULL,
    results_digest CHAR(64) NOT NULL,
    results_count BIGINT NOT NULL,
    keyed BOOLEAN NOT NULL,
    signature CHAR(64) NOT NULL,
    object_key VARCHAR(160)
);

CREATE INDEX IF NOT EXISTS idx_wash_audit_session_event
    ON wash_audit_events (session_id, event_id DESC);

CREATE INDEX IF NOT EXISTS idx_wash_audit_event_time
    ON wash_audit_events (occurred_at_epoch_ms DESC);

CREATE TABLE IF NOT EXISTS station_enrollment_codes (
    code_hash VARCHAR(64) PRIMARY KEY,
    station_name VARCHAR(80) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    created_at_epoch_ms BIGINT NOT NULL,
    expires_at_epoch_ms BIGINT NOT NULL,
    consumed_at_epoch_ms BIGINT,
    CONSTRAINT chk_station_enrollment_expiry CHECK (expires_at_epoch_ms > created_at_epoch_ms)
);

CREATE INDEX IF NOT EXISTS idx_station_enrollment_expiry
    ON station_enrollment_codes (expires_at_epoch_ms);

CREATE TABLE IF NOT EXISTS handwash_stations (
    station_id VARCHAR(36) PRIMARY KEY,
    station_name VARCHAR(80) NOT NULL,
    credential_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at_epoch_ms BIGINT NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    revoked_at_epoch_ms BIGINT,
    last_started_at_epoch_ms BIGINT,
    active_session_id VARCHAR(36),
    active_request_id VARCHAR(36),
    producer_client_id VARCHAR(128),
    activation_hash VARCHAR(64),
    activation_expires_at_epoch_ms BIGINT,
    activated_at_epoch_ms BIGINT,
    CONSTRAINT chk_station_active_reservation CHECK (
        (active_session_id IS NULL AND active_request_id IS NULL)
        OR (active_session_id IS NOT NULL AND active_request_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_handwash_stations_created
    ON handwash_stations (created_at_epoch_ms DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_handwash_stations_activation
    ON handwash_stations (activation_hash);

CREATE TABLE IF NOT EXISTS station_operator_access_codes (
    code_id VARCHAR(36) PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL UNIQUE,
    station_id VARCHAR(36) NOT NULL,
    target_email VARCHAR(254) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    created_at_epoch_ms BIGINT NOT NULL,
    consumed_at_epoch_ms BIGINT,
    consumed_by VARCHAR(128),
    revoked_at_epoch_ms BIGINT,
    CONSTRAINT fk_operator_code_station FOREIGN KEY (station_id) REFERENCES handwash_stations(station_id)
);

CREATE INDEX IF NOT EXISTS idx_operator_codes_station_created
    ON station_operator_access_codes (station_id, created_at_epoch_ms DESC);

CREATE TABLE IF NOT EXISTS station_operator_grants (
    cognito_subject VARCHAR(128) PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    station_id VARCHAR(36) NOT NULL,
    granted_by VARCHAR(128) NOT NULL,
    granted_at_epoch_ms BIGINT NOT NULL,
    revoked_at_epoch_ms BIGINT,
    CONSTRAINT fk_operator_grant_station FOREIGN KEY (station_id) REFERENCES handwash_stations(station_id)
);

CREATE INDEX IF NOT EXISTS idx_operator_grants_station
    ON station_operator_grants (station_id, revoked_at_epoch_ms);

CREATE TABLE IF NOT EXISTS api_keys (
    key_id VARCHAR(16) PRIMARY KEY,
    station_id VARCHAR(36) NOT NULL,
    label VARCHAR(80) NOT NULL,
    secret_hash VARCHAR(64) NOT NULL,
    scopes VARCHAR(32) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    created_at_epoch_ms BIGINT NOT NULL,
    last_used_at_epoch_ms BIGINT,
    last_used_ip VARCHAR(64),
    revoked_at_epoch_ms BIGINT,
    revoked_by VARCHAR(128),
    CONSTRAINT fk_api_key_station FOREIGN KEY (station_id) REFERENCES handwash_stations(station_id)
);

CREATE INDEX IF NOT EXISTS idx_api_keys_station ON api_keys (station_id, revoked_at_epoch_ms);

