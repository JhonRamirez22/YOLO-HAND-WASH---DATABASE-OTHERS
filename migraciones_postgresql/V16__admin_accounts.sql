-- Local ADMIN accounts for on-premises deployments (password + TOTP). The TOTP secret is stored AES-GCM encrypted,
-- the password as a bcrypt hash and session tokens only as SHA-256.
CREATE TABLE admin_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    totp_secret_enc VARCHAR(200) NOT NULL,
    totp_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
