CREATE TABLE IF NOT EXISTS failed_attempts (
    session_id VARCHAR(36) NOT NULL,
    attempt_number INTEGER NOT NULL,
    result VARCHAR(32) NOT NULL,
    reason VARCHAR(128) NOT NULL,
    duration_ms BIGINT NOT NULL,
    payload_json CLOB NOT NULL,
    created_at_epoch_ms BIGINT NOT NULL,
    CONSTRAINT pk_failed_attempts PRIMARY KEY (session_id, attempt_number),
    CONSTRAINT chk_failed_attempts_number CHECK (attempt_number > 0),
    CONSTRAINT chk_failed_attempts_duration CHECK (duration_ms >= 0)
);

CREATE INDEX IF NOT EXISTS idx_failed_attempts_created
    ON failed_attempts (created_at_epoch_ms);

CREATE TABLE IF NOT EXISTS wash_encounters (
    session_id VARCHAR(36) PRIMARY KEY,
    protocol_code VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    started_at_epoch_ms BIGINT NOT NULL,
    ended_at_epoch_ms BIGINT,
    model_version VARCHAR(128) NOT NULL,
    model_sha256 VARCHAR(64) NOT NULL,
    dataset_version VARCHAR(128) NOT NULL,
    attempts_restarted INTEGER NOT NULL DEFAULT 0,
    producer_client_id VARCHAR(128),
    producer_epoch VARCHAR(64),
    protocol_profile_version INTEGER,
    CONSTRAINT chk_wash_encounters_attempts CHECK (attempts_restarted >= 0)
);

CREATE INDEX IF NOT EXISTS idx_wash_encounters_started
    ON wash_encounters (started_at_epoch_ms);

CREATE TABLE IF NOT EXISTS wash_audit_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36),
    event_type VARCHAR(48) NOT NULL,
    actor_subject VARCHAR(128),
    step_code VARCHAR(64),
    decision_code VARCHAR(48) NOT NULL,
    reason_code VARCHAR(80),
    attempt_number INTEGER,
    frame_sequence BIGINT,
    confidence DOUBLE PRECISION,
    occurred_at_epoch_ms BIGINT NOT NULL,
    CONSTRAINT chk_wash_audit_confidence
        CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);

